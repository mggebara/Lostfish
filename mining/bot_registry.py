"""Which Lichess bots can we model exactly? Public bios of online bots, grepped for engine, net and nodes.

    python -m mining.bot_registry --out data/bots/registry.json --md docs/REPLICABLE_BOTS.md

No token needed: `GET /api/bot/online` lists bots currently online, `GET /api/user/{id}` gives the
profile bio when the listing lacks it (one request per second). A bot is "replicable" when its bio names
an Lc0/Leela or Maia setup; the JSON keeps every bot seen with the raw bio for manual review, the Markdown
table lists the replicable ones by blitz rating. Run it a few times on different days: only online bots
are listed, so the set grows per run (`--merge` keeps earlier rows).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import time
from pathlib import Path
from typing import Any

from mining.fetch_games import Lichess, slim_user

ENGINES = {
    "lc0": re.compile(r"\b(lc0|leela|lczero|leela chess zero)\b", re.IGNORECASE),
    "maia": re.compile(r"\bmaia\b", re.IGNORECASE),
    "stockfish": re.compile(r"\b(stockfish|sf ?1\d(?:\.\d)?)\b", re.IGNORECASE),
    "komodo": re.compile(r"\b(komodo|dragon)\b", re.IGNORECASE),
    "custom": re.compile(
        r"\b(my own|own engine|written in|from scratch|homemade|home-made)\b", re.IGNORECASE
    ),
}
NET_RE = re.compile(
    r"\b(BT[0-9]|T[0-9]{1,2}(?:-[0-9]+x[0-9]+)?|t[0-9]{2}-[0-9]{3,}|[0-9]{6}|maia[- ]?[0-9]{4}"
    r"|[0-9]{2,3}x[0-9]{1,2}(?:x[0-9]+h)?|BT[0-9]-[0-9]+)\b",
    re.IGNORECASE,
)
NODES_RE = re.compile(
    r"(\d[\d,.]*\s*[kKmM]?)\s*(?:nodes|n/move|nodes/move|visits|playouts)\b", re.IGNORECASE
)


def classify(bio: str) -> dict[str, Any]:
    """Engine family hits, net names and node counts mentioned in a bio (empty when nothing matches)."""
    text = bio or ""
    engines = [name for name, rx in ENGINES.items() if rx.search(text)]
    nets = sorted({m.group(1) for m in NET_RE.finditer(text)})
    nodes = sorted({m.group(1).strip() for m in NODES_RE.finditer(text)})
    replicable = ("lc0" in engines or "maia" in engines) and "custom" not in engines
    return {"engines": engines, "nets": nets, "nodes": nodes, "replicable": replicable}


def bot_row(user: dict[str, Any], bio: str, seen: str) -> dict[str, Any]:
    slim = slim_user(user)
    return slim | classify(bio) | {"bio": bio.strip()[:600], "seen": seen}


def collect(client: Lichess, nb: int, *, fetch_bios: bool = True) -> list[dict[str, Any]]:
    seen = time.strftime("%Y-%m-%d")
    rows = []
    for u in client.online_bots(nb):
        profile = u.get("profile") or {}
        bio = str(profile.get("bio") or "")
        if not bio and fetch_bios:
            r = client.request("GET", f"/api/user/{u.get('id') or u.get('username')}")
            if r.ok:
                bio = str((r.json().get("profile") or {}).get("bio") or "")
        rows.append(bot_row(u, bio, seen))
    return rows


def markdown(rows: list[dict[str, Any]]) -> str:
    rep = [r for r in rows if r["replicable"]]
    rep.sort(key=lambda r: -(r["perfs"].get("blitz") or {}).get("rating", 0))
    out = [
        "# Replicable Lichess bots (bio names an Lc0/Leela or Maia setup)",
        "",
        (
            f"Generated by `mining/bot_registry.py`; {len(rows)} online bots seen, {len(rep)} replicable. "
            "Nets/nodes are regex hits on the bio: confirm by reading it before building a profile."
        ),
        "",
        "| bot | blitz | bullet | engines | nets | nodes | bio (excerpt) |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rep:
        p = r["perfs"]
        blitz = f"{p['blitz']['rating']} ({p['blitz']['games']})" if "blitz" in p else "-"
        bullet = f"{p['bullet']['rating']} ({p['bullet']['games']})" if "bullet" in p else "-"
        excerpt = re.sub(r"\s+", " ", r["bio"])[:160].replace("|", "/")
        out.append(
            f"| {r['username']} | {blitz} | {bullet} | {', '.join(r['engines'])} | "
            f"{', '.join(r['nets'])} | {', '.join(r['nodes'])} | {excerpt} |"
        )
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--out", default="data/bots/registry.json")
    ap.add_argument("--md", default="docs/REPLICABLE_BOTS.md")
    ap.add_argument("--nb", type=int, default=300, help="max online bots to list")
    ap.add_argument("--merge", action="store_true", help="keep rows from an earlier --out")
    args = ap.parse_args(argv)
    out = Path(args.out)
    old: dict[str, dict[str, Any]] = {}
    if args.merge and out.exists():
        old = {r["id"]: r for r in json.loads(out.read_text())}
    rows = collect(Lichess(), args.nb)
    merged = old | {r["id"]: r for r in rows}
    final = sorted(merged.values(), key=lambda r: r["username"].lower())
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(final, indent=1))
    Path(args.md).write_text(markdown(final))
    print(
        f"{len(rows)} online bots, {len(final)} in registry, {sum(r['replicable'] for r in final)} replicable"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
